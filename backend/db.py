def connect(path: Path | None = None) -> sqlite3.Connection:
    # FastAPI may open a request's connection in one worker thread and close it in another.
    # Each connection is still used by one request at a time, so cross-thread use is safe here.
    conn = sqlite3.connect(path or DB_PATH, timeout=10, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


@contextmanager
def db_session(path: Path | None = None):
    """Open, commit and always close (Windows keeps files locked while a connection is open)."""
    conn = connect(path)
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def migrate_schema(conn: sqlite3.Connection) -> None:
    """Small in-place upgrades for databases built by an older version (no data is lost)."""
    sql = conn.execute("SELECT sql FROM sqlite_master WHERE name = 'receipts'").fetchone()
    if sql and "'rejected'" not in sql[0]:
        # SQLite can't change a CHECK constraint, so rebuild the table with the same rows.
        conn.executescript("""
            ALTER TABLE receipts RENAME TO receipts_old;
            CREATE TABLE receipts (
                id INTEGER PRIMARY KEY,
                upload_id INTEGER REFERENCES uploads(id),
                status TEXT NOT NULL CHECK (status IN ('pending','confirmed','rejected')),
                reject_reason TEXT,
                vendor TEXT NOT NULL DEFAULT '',
                date TEXT NOT NULL,
                total REAL NOT NULL DEFAULT 0,
                items TEXT NOT NULL DEFAULT '[]',
                flags TEXT NOT NULL DEFAULT '[]',
                created_at TEXT NOT NULL
            );
            INSERT INTO receipts(id, upload_id, status, vendor, date, total, items, flags, created_at)
                SELECT id, upload_id, status, vendor, date, total, items, flags, created_at FROM receipts_old;
            DROP TABLE receipts_old;
        """)
        conn.commit()


def ensure_db() -> None:
    """Build the demo database on first run so a fresh clone works with no setup step."""
    from .seed import build, sync_catalog
    if not DB_PATH.exists():
        build()
        return
    conn = connect()
    try:
        migrate_schema(conn)
        sync_catalog(conn)  # new add-ons / gallery photos without wiping orders or history
    finally:
        conn.close()


def get_settings(conn: sqlite3.Connection) -> dict[str, Any]:
    out = dict(DEFAULT_SETTINGS)
    for row in conn.execute("SELECT key, value FROM settings"):
        out[row["key"]] = json.loads(row["value"])
    return out


def set_settings(conn: sqlite3.Connection, values: dict[str, Any]) -> dict[str, Any]:
    for k, v in values.items():
        if k not in DEFAULT_SETTINGS:
            raise ValueError(f"Unknown setting: {k}")
        conn.execute("INSERT INTO settings(key, value) VALUES(?, ?) "
                     "ON CONFLICT(key) DO UPDATE SET value = excluded.value", (k, json.dumps(v)))
    conn.commit()
    return get_settings(conn)


def jl(value: str | None, default: Any = None) -> Any:
    if value is None:
        return default
    try:
        return json.loads(value)
    except (TypeError, json.JSONDecodeError):
        return default


def jd(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)
